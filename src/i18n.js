// Lightweight i18n. Language is a per-device preference (localStorage), not synced
// between partners. Components read strings via tr('key'); changing the language
// updates a module variable and App re-renders the tree.

const STORE_KEY = 'lang';

let currentLang = (() => {
  try { return localStorage.getItem(STORE_KEY) === 'en' ? 'en' : 'ru'; } catch { return 'ru'; }
})();

export function getLanguage() { return currentLang; }

export function setLanguage(lang) {
  currentLang = lang === 'en' ? 'en' : 'ru';
  try { localStorage.setItem(STORE_KEY, currentLang); } catch { /* ignore */ }
}

export function tr(key, params) {
  const table = DICT[currentLang] || DICT.ru;
  let s = (key in table) ? table[key] : (DICT.ru[key] ?? key);
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, params[k]);
  return s;
}

